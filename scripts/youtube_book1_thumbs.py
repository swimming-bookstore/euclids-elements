class V2:
    def __init__(self, x: float, y: float):
        self.x = float(x)
        self.y = float(y)

    def add(self, o: V2) -> V2:
        return V2(self.x + o.x, self.y + o.y)

    def sub(self, o: V2) -> V2:
        return V2(self.x - o.x, self.y - o.y)

    def mul(self, s: float) -> V2:
        return V2(self.x * s, self.y * s)

    def dist(self, o: V2) -> float:
        return math.hypot(self.x - o.x, self.y - o.y)

    def polar(self, r: float, deg: float) -> V2:
        a = math.radians(deg)
        return V2(self.x + r * math.cos(a), self.y + r * math.sin(a))

    def toward(self, o: V2, dist: float) -> V2:
        n = self.dist(o) or 1.0
        return V2(self.x + (o.x - self.x) / n * dist, self.y + (o.y - self.y) / n * dist)

    def xy(self) -> tuple[float, float]:
        return (self.x, self.y)


class Place:
    def __init__(self, deg: float):
        self.deg = deg


class Eval:
    def __init__(self, env: dict):
        self.env = env
        self.s = ""
        self.i = 0

    def eval(self, s: str):
        self.s = s.strip()
        self.i = 0
        v = self.expr()
        self.skip()
        if self.i < len(self.s):
            raise SystemExit(f"leftover {self.s[self.i:]!r} in {s!r}")
        return v

    def skip(self) -> None:
        while self.i < len(self.s) and self.s[self.i].isspace():
            self.i += 1

    def peek(self) -> str:
        self.skip()
        return self.s[self.i] if self.i < len(self.s) else ""

    def startswith(self, t: str) -> bool:
        self.skip()
        return self.s.startswith(t, self.i)

    def expr(self):
        v = self.term()
        while (ch := self.peek()) and ch in "+-":
            op = self.s[self.i]
            self.i += 1
            r = self.term()
            v = v + r if op == "+" else v - r
        return v

    def term(self):
        v = self.unary()
        while (ch := self.peek()) and ch in "*/":
            op = self.s[self.i]
            self.i += 1
            r = self.unary()
            v = v * r if op == "*" else v / r
        return v

    def unary(self):
        if self.peek() == "-":
            self.i += 1
            return -self.unary()
        return self.postfix()

    def postfix(self):
        v = self.primary()
        while self.peek() == ".":
            self.i += 1
            name = self.ident()
            self.expect("(")
            args = self.args()
            self.expect(")")
            v = getattr(v, name)(*args)
        return v

    def primary(self):
        self.skip()
        if self.startswith("V2::new"):
            self.i += len("V2::new")
            self.expect("(")
            x, y = self.args()
            self.expect(")")
            return V2(x, y)
        if self.startswith("Place::Deg"):
            self.i += len("Place::Deg")
            self.expect("(")
            deg = self.expr()
            self.expect(")")
            return Place(float(deg))
        if self.startswith("Place::"):
            self.i += len("Place::")
            name = self.ident()
            if name not in PLACE_DEG:
                raise SystemExit(f"unknown Place::{name}")
            return Place(PLACE_DEG[name])
        ch = self.peek()
        if ch == "(":
            self.i += 1
            v = self.expr()
            if self.peek() == ",":
                pair = [v]
                while self.peek() == ",":
                    self.i += 1
                    if self.peek() == ")":
                        break
                    pair.append(self.expr())
                self.expect(")")
                return tuple(pair)
            self.expect(")")
            return v
        if ch == "&":
            self.i += 1
            return self.array()
        if ch == "[":
            return self.array()
        if ch == '"':
            return self.string()
        if ch.isdigit() or ch == ".":
            return self.number()
        name = self.ident()
        if name == "true":
            return True
        if name == "false":
            return False
        if name not in self.env:
            raise SystemExit(f"unknown name {name}")
        return self.env[name]

    def array(self):
        self.expect("[")
        out = []
        if self.peek() != "]":
            out.append(self.expr())
            while self.peek() == ",":
                self.i += 1
                if self.peek() == "]":
                    break
                out.append(self.expr())
        self.expect("]")
        return out

    def args(self):
        out = []
        if self.peek() not in ")]":
            out.append(self.expr())
            while self.peek() == ",":
                self.i += 1
                if self.peek() in ")]":
                    break
                out.append(self.expr())
        return out

    def string(self) -> str:
        self.expect('"')
        j = self.s.index('"', self.i)
        v = self.s[self.i : j]
        self.i = j + 1
        return v

    def number(self) -> float:
        self.skip()
        j = self.i
        while j < len(self.s) and (self.s[j].isdigit() or self.s[j] in "._"):
            j += 1
        if self.s.startswith("f64", j) or self.s.startswith("f32", j):
            j += 3
        raw = self.s[self.i : j].replace("_f64", "").replace("_f32", "").replace("_", "")
        self.i = j
        return float(raw)

    def ident(self) -> str:
        self.skip()
        j = self.i
        while j < len(self.s) and (self.s[j].isalnum() or self.s[j] == "_"):
            j += 1
        if j == self.i:
            raise SystemExit(f"expected ident at {self.s[self.i : self.i + 20]!r}")
        v = self.s[self.i : j]
        self.i = j
        return v

    def expect(self, t: str) -> None:
        self.skip()
        if not self.s.startswith(t, self.i):
            raise SystemExit(f"expected {t!r} at {self.s[self.i : self.i + 24]!r}")
        self.i += len(t)


class Scene:
    def __init__(self):
        self.pts: dict[str, V2] = {}
        self.labels: dict[str, tuple[V2, float, float]] = {}
        self.segs: list[tuple[str, str]] = []
        self.circs: list[tuple[str, float]] = []
        self.arc_list: list[tuple[V2, V2, V2]] = []
        self.dot_pts: list[V2] = []
        self.clip_box: tuple[V2, V2] | None = None
        # Points the fit ignores. A light square the plate does not draw
        # must not shrink the figure.
        self.fit_skip: set[str] = set()
        # Arm ends of a given angle (I.42's Dleft, Dright). Not lettered.
        self.arms: dict[str, V2] = {}

    def at(self, name: str) -> V2:
        if name in self.pts:
            return self.pts[name]
        if name in self.arms:
            return self.arms[name]
        raise SystemExit(f"unknown point {name}")

    def pin(self, name: str, p: V2) -> None:
        self.pts[name] = p

    def _label(self, name: str, at: V2, place: Place, r_em: float = LETTER_R) -> None:
        self.labels[name] = (at, place.deg, r_em)

    def put(self, name: str, p: V2, place: Place) -> None:
        self.pin(name, p)
        self._label(name, p, place)

    def put_line_end(self, name: str, p: V2, left: bool) -> None:
        self.put(name, p, Place(135.0 if left else 45.0))

    def level(self, name: str, of: str, x: float, place: Place) -> None:
        self.put(name, V2(x, self.at(of).y), place)

    def plumb(self, name: str, of: str, y: float, place: Place) -> None:
        self.put(name, V2(self.at(of).x, y), place)

    def corner(self, name: str, x_of: str, y_of: str, place: Place) -> None:
        self.put(name, V2(self.at(x_of).x, self.at(y_of).y), place)

    def meet(self, name: str, a: str, b: str, c: str, d: str, place: Place) -> None:
        pa, pb, pc, pd = self.at(a), self.at(b), self.at(c), self.at(d)
        den = (pa.x - pb.x) * (pc.y - pd.y) - (pa.y - pb.y) * (pc.x - pd.x)
        if abs(den) < 1e-12:
            raise SystemExit(f"{a}{b} parallel to {c}{d}")
        t = ((pa.x - pc.x) * (pc.y - pd.y) - (pa.y - pc.y) * (pc.x - pd.x)) / den
        self.put(name, V2(pa.x + t * (pb.x - pa.x), pa.y + t * (pb.y - pa.y)), place)

    def put_r(self, name: str, p: V2, place: Place, r_em: float) -> None:
        self.pin(name, p)
        self._label(name, p, place, r_em)

    def glyph(self, name: str, at: V2) -> None:
        # A plate capital whose center is not a heading from a vertex.
        # The center is the measured glyph, so the letter is not offset
        # a second time.
        self.pin(name, at)
        self.labels[name] = (at, 90.0, 0.0)

    def highlight_arc(self, _a: str, _b: str, _center: str) -> None:
        # Lit only in the demo. The card washes the pentagon, not the arcs.
        return

    def named_outline(self, _letters: str, boundary: list) -> None:
        self.chain(list(boundary))
        if boundary and boundary[0] != boundary[-1]:
            self.join(boundary[-1], boundary[0])

    def label(self, name: str, place: Place) -> None:
        self._label(name, self.at(name), place)

    def label_r(self, name: str, place: Place, r_em: float) -> None:
        self._label(name, self.at(name), place, r_em)

    def label_at(self, name: str, at: V2, place: Place) -> None:
        self._label(name, at, place)

    def polar(self, name: str, origin: str, r: float, deg: float, place: Place) -> None:
        self.put(name, self.at(origin).polar(r, deg), place)

    def ray(self, name: str, origin: str, through: str, dist: float, place: Place) -> None:
        self.put(name, self.at(origin).toward(self.at(through), dist), place)

    def on_line(self, name: str, a: str, b: str, t: float, place: Place) -> None:
        pa, pb = self.at(a), self.at(b)
        self.pin(name, V2(pa.x + (pb.x - pa.x) * t, pa.y + (pb.y - pa.y) * t))
        self._label(name, self.at(name), place)

    def _circle_letter(self, name: str, center: str, through: str, deg: float, inside: bool) -> None:
        c = self.at(center)
        p = c.polar(c.dist(self.at(through)), deg)
        self.pin(name, p)
        self._label(name, p, Place(deg + 180.0 if inside else deg))

    def on_circle(self, name: str, center: str, through: str, deg: float) -> None:
        self._circle_letter(name, center, through, deg, False)

    def in_circle(self, name: str, center: str, through: str, deg: float) -> None:
        self._circle_letter(name, center, through, deg, True)

    def join(self, a: str, b: str) -> None:
        self.segs.append((a, b))

    def chain(self, names: list[str]) -> None:
        for a, b in zip(names, names[1:]):
            self.join(a, b)

    def base(self, a: str, b: str) -> None:
        self.join(a, b)

    def named_line(self, _letters: str, a: str, b: str) -> None:
        self.join(a, b)

    def circle(self, _letters: str, center: str, through: str) -> None:
        c = self.at(center)
        self.circs.append((center, c.dist(self.at(through))))

    def circle_r(self, _letters: str, center: str, r: float) -> None:
        self.circs.append((center, r))

    def bow(self, a: str, b: str, sag: float) -> None:
        pa, pb = self.at(a), self.at(b)
        mid = V2((pa.x + pb.x) / 2, (pa.y + pb.y) / 2)
        nx, ny = pa.y - pb.y, pb.x - pa.x
        nlen = math.hypot(nx, ny) or 1.0
        via = V2(mid.x + nx / nlen * sag, mid.y + ny / nlen * sag)
        self.arc_list.append((pa, pb, via))

    def dots(self, names: list[str]) -> None:
        for name in names:
            self.dot_pts.append(self.at(name))

    def dot_at(self, _name: str, p: V2) -> None:
        self.dot_pts.append(p)

    def clip(self, a: V2, b: V2) -> None:
        self.clip_box = (a, b)

    def given_angle(
        self,
        name: str,
        from_: str,
        vertex: tuple[float, float],
        left: tuple[float, float],
        right: tuple[float, float],
        glyph: V2,
    ) -> None:
        self.given_angle_arms(name, from_, vertex, [left, right], glyph)

    def given_angle_arms(
        self,
        name: str,
        from_: str,
        vertex: tuple[float, float],
        arms: list,
        glyph: V2,
    ) -> None:
        # Same construction as Diagram::given_angle_arms: vertex from a point,
        # then each arm, then the plate glyph. The strokes share one mark.
        v = self.at(from_).polar(vertex[0], vertex[1])
        self.pin(name, v)
        side = ["left", "right"]
        for i, arm in enumerate(arms):
            length, heading = arm
            end = v.polar(length, heading)
            suffix = side[i] if i < 2 else f"arm{i}"
            self.arms[f"{name}{suffix}"] = end
            self.segs.append((name, f"{name}{suffix}"))
        # The capital is the plate glyph, not an offset from the vertex.
        self.labels[name] = (glyph, 90.0, 0.0)

    def region(self, _name: str, _boundary: list) -> None:
        # Opposite-corner names (I.43's EH, BK). The card washes the
        # complements; it does not redraw the plate.
        return

    def along(self, _name: str, _points: list) -> None:
        # A bent spoken line (I.47's GC as G–A–C). The strokes are already
        # drawn; the card does not light the name.
        return

    def meet_pin(self, name: str, a: str, b: str, c: str, d: str) -> None:
        pa, pb, pc, pd = self.at(a), self.at(b), self.at(c), self.at(d)
        den = (pa.x - pb.x) * (pc.y - pd.y) - (pa.y - pb.y) * (pc.x - pd.x)
        if abs(den) < 1e-12:
            raise SystemExit(f"{a}{b} parallel to {c}{d}")
        t = ((pa.x - pc.x) * (pc.y - pd.y) - (pa.y - pc.y) * (pc.x - pd.x)) / den
        self.pin(name, V2(pa.x + t * (pb.x - pa.x), pa.y + t * (pb.y - pa.y)))

    def bounds(self) -> tuple[float, float, float, float]:
        if self.clip_box:
            a, b = self.clip_box
            return min(a.x, b.x), min(a.y, b.y), max(a.x, b.x), max(a.y, b.y)
        xs: list[float] = []
        ys: list[float] = []

        def add(p: V2) -> None:
            xs.append(p.x)
            ys.append(p.y)

        for a, b in self.segs:
            if a in self.fit_skip or b in self.fit_skip:
                continue
            add(self.at(a))
            add(self.at(b))
        for name, r in self.circs:
            c = self.at(name)
            xs.extend((c.x - r, c.x + r))
            ys.extend((c.y - r, c.y + r))
        for a, b, via in self.arc_list:
            add(a)
            add(b)
            add(via)
        for p in self.dot_pts:
            add(p)
        for name in self.labels:
            if name in self.pts:
                add(self.pts[name])
        if not xs:
            return 0.0, 0.0, 1.0, 1.0
        return min(xs), min(ys), max(xs), max(ys)


def statements(src: str) -> list[str]:
    lines = []
    for line in src.splitlines():
        if "//" in line:
            line = line[: line.index("//")]
        lines.append(line)
    text = "\n".join(lines)
    out = []
    i, n = 0, len(text)
    while i < n:
        while i < n and text[i].isspace():
            i += 1
        if i >= n:
            break
        if text.startswith("let ", i) or text.startswith("d.", i):
            start = i
            depth = 0
            while i < n:
                c = text[i]
                if c in "({[":
                    depth += 1
                elif c in ")}]":
                    depth = max(0, depth - 1)
                elif c == ";" and depth == 0:
                    i += 1
                    break
                i += 1
            out.append(text[start:i].strip())
        else:
            i += 1
    return out


def load_scene(n: int, body: str) -> Scene:
    env: dict = {}
    ev = Eval(env)
    scene = Scene()
    for stmt in statements(body):
        if stmt.startswith("let mut "):
            continue
        if stmt.startswith("let "):
            rest = stmt[4:].strip().rstrip(";").strip()
            name, expr = rest.split("=", 1)
            name = name.strip()
            expr = expr.strip()
            if expr.startswith("{"):
                env[name] = eval_block(expr, ev, env)
            else:
                env[name] = ev.eval(expr)
            continue
        call = stmt[2:].strip().rstrip(";").strip()
        m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\((.*)\)\s*$", call, re.S)
        if not m:
            raise SystemExit(f"I.{n}: cannot parse {stmt}")
        method, arg_src = m.group(1), m.group(2)
        args = ev.eval(f"[{arg_src}]")
        getattr(scene, method)(*args)
    return scene


def eval_block(expr: str, ev: Eval, env: dict):
    inner = expr.strip()
    if not (inner.startswith("{") and inner.endswith("}")):
        raise SystemExit(f"not a block: {expr!r}")
    inner = inner[1:-1].strip()
    parts: list[str] = []
    i, n = 0, len(inner)
    while i < n:
        while i < n and inner[i].isspace():
            i += 1
        if i >= n:
            break
        start = i
        depth = 0
        while i < n:
            c = inner[i]
            if c in "({[":
                depth += 1
            elif c in ")}]":
                depth -= 1
            elif c == ";" and depth == 0:
                i += 1
                parts.append(inner[start:i].strip())
                break
            i += 1
        else:
            parts.append(inner[start:].strip())
            break
    value = None
    for part in parts:
        if part.startswith("let "):
            _bind(part if part.endswith(";") else part + ";", ev, env)
        else:
            value = ev.eval(part.rstrip(";").strip())
    if value is None:
        raise SystemExit(f"block has no value: {expr!r}")
    return value


def _bind(stmt: str, ev: Eval, env: dict) -> None:
    rest = stmt[4:].strip().rstrip(";").strip()
    name, expr = rest.split("=", 1)
    env[name.strip()] = ev.eval(expr.strip())


def functions() -> dict[int, str]:
    text = (ROOT / "src" / "figure" / "book1.rs").read_text()
    out = {}
    for chunk in re.split(r"\npub fn ", text)[1:]:
        m = re.match(r"book1_prop(\d+)", chunk)
        if not m:
            continue
        n = int(m.group(1))
        body = chunk.split("{", 1)[1]
        # Function body ends at the matching brace. The chunk already stops
        # at the next pub fn, and the last line is the closing brace.
        depth = 1
        i = 0
        while i < len(body) and depth:
            if body[i] == "{":
                depth += 1
            elif body[i] == "}":
                depth -= 1
            i += 1
        out[n] = body[: i - 1]
    return out


def rgb(c):
    return tuple(v / 255 for v in c)


def ink_of(book: int) -> tuple[int, int, int]:
    # Book II strokes sit on cool paper, so the ink is teal, not the Book I black.
    return TEAL if book == 2 else INK


def paint_ground(cr, book: int) -> None:
    """Book I is the cream plate. Book II is cool paper, with no header band."""
    if book != 2:
        pat = cairo.LinearGradient(0, 0, W, H)
        pat.add_color_stop_rgb(0, *rgb(CREAM))
        pat.add_color_stop_rgb(1, 0.965, 0.925, 0.875)
        cr.set_source(pat)
        cr.paint()
        return
    pat = cairo.LinearGradient(0, 0, 0, H)
    pat.add_color_stop_rgb(0, *rgb(PAPER2_0))
    pat.add_color_stop_rgb(1, *rgb(PAPER2_1))
    cr.set_source(pat)
    cr.paint()


def font(cr, size, bold=False, italic=False):
    cr.select_font_face(
        "Liberation Serif",
        cairo.FONT_SLANT_ITALIC if italic else cairo.FONT_SLANT_NORMAL,
        cairo.FONT_WEIGHT_BOLD if bold else cairo.FONT_WEIGHT_NORMAL,
    )
    cr.set_font_size(size)


def arc_points(a: V2, b: V2, via: V2, n: int = 48) -> list[tuple[float, float]]:
    ax, ay, bx, by, cx, cy = a.x, a.y, b.x, b.y, via.x, via.y
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    if abs(d) < 1e-9:
        return [(ax, ay), (bx, by)]
    a2, b2, c2 = ax * ax + ay * ay, bx * bx + by * by, cx * cx + cy * cy
    ux = (a2 * (by - cy) + b2 * (cy - ay) + c2 * (ay - by)) / d
    uy = (a2 * (cx - bx) + b2 * (ax - cx) + c2 * (bx - ax)) / d
    r = math.hypot(ax - ux, ay - uy)

    def ang(x, y):
        return math.atan2(y - uy, x - ux) % math.tau

    aa, bb, vv = ang(ax, ay), ang(bx, by), ang(cx, cy)
    sweep = (bb - aa) % math.tau
    if (vv - aa) % math.tau > sweep:
        sweep -= math.tau
    return [
        (ux + r * math.cos(aa + sweep * i / n), uy + r * math.sin(aa + sweep * i / n))
        for i in range(n + 1)
    ]


def angle_wedge(scene: Scene, arm: str, vertex: str, other: str, radius: float) -> list[V2]:
    """Sector of ∠(arm, vertex, other), radius in plate units.

    The lesser turn is the angle the figure draws. A reflex would fill the
    outside and read as the triangle again.
    """
    v = scene.at(vertex)
    a = math.atan2((scene.at(arm).y - v.y), (scene.at(arm).x - v.x))
    b = math.atan2((scene.at(other).y - v.y), (scene.at(other).x - v.x))
    sweep = (b - a + math.pi) % math.tau - math.pi
    n = max(12, int(abs(sweep) / math.tau * 64))
    pts = [v]
    for i in range(n + 1):
        t = a + sweep * i / n
        pts.append(V2(v.x + radius * math.cos(t), v.y + radius * math.sin(t)))
    return pts


def angle_square(scene: Scene, arm: str, vertex: str, other: str, side: float) -> list[V2]:
    """Square in ∠(arm, vertex, other). Side equals the pie radius.

    The two sides lie on the arms. A right-angle reads as a square; a pie
    would read as any angle. The lesser turn is the angle the figure draws.
    """
    v = scene.at(vertex)
    a = math.atan2((scene.at(arm).y - v.y), (scene.at(arm).x - v.x))
    b = math.atan2((scene.at(other).y - v.y), (scene.at(other).x - v.x))
    sweep = (b - a + math.pi) % math.tau - math.pi
    # Unit steps along the arms, then the outer corner. Sweep sign keeps
    # the corner inside the angle rather than on the reflex side.
    turn = 1.0 if sweep >= 0 else -1.0
    ca, sa = math.cos(a), math.sin(a)
    # Perpendicular to the first arm, turned into the angle.
    px, py = -sa * turn, ca * turn
    return [
        v,
        V2(v.x + side * ca, v.y + side * sa),
        V2(v.x + side * (ca + px), v.y + side * (sa + py)),
        V2(v.x + side * px, v.y + side * py),
    ]


def square_outward(p: V2, q: V2, away: V2) -> list[V2]:
    """Square on directed pq, on the side away from `away`. y is up.

    The two outer corners follow q, then p, so a wash p–q–outer–outer
    walks the boundary without crossing.
    """
    left = V2(-(q.y - p.y), q.x - p.x)
    right = V2(q.y - p.y, -(q.x - p.x))
    mid = V2((p.x + q.x) / 2, (p.y + q.y) / 2)
    left_of = mid.add(left.mul(0.5)).dist(away)
    right_of = mid.add(right.mul(0.5)).dist(away)
    side = left if left_of > right_of else right
    return [p, q, q.add(side), p.add(side)]


def prepare(n: int, scene: Scene) -> None:
    """Check the angle marks. I.48 pins the squares the plate does not draw."""
    if n == 48:
        # The enunciation is the squares on the sides of ABC, and the
        # right-angle they imply. The plate draws neither square. AD and DC
        # are the construction, so the card keeps them and draws the squares
        # outward. The side the square stands on is already a plate stroke.
        for key, pn, qn, away in (
            ("Bc", "B", "C", "A"),
            ("Ba", "B", "A", "C"),
            ("Ac", "A", "C", "B"),
        ):
            pts = square_outward(scene.at(pn), scene.at(qn), scene.at(away))
            scene.pin(f"{key}1", pts[2])
            scene.pin(f"{key}2", pts[3])
            # The plate is ABC. Counting the outer corners would shrink it,
            # and a fixed-size right-angle mark would grow with that shrink.
            scene.fit_skip.add(f"{key}1")
            scene.fit_skip.add(f"{key}2")
        # The edges are not stroked. They exist so the wash has corners.
        for u, v in SQUARE_QUIET.get(n, ()):
            scene.join(u, v)
    for group in ANGLES.get(n, []):
        for arm, vertex, other in group:
            for name in (arm, vertex, other):
                # Arm ends of a given angle live in scene.arms, not scene.pts.
                try:
                    scene.at(name)
                except SystemExit:
                    raise SystemExit(f"I.{n}: angle {arm}{vertex}{other} missing {name}") from None


def render(n: int, scene: Scene, out: Path, book: int = 1, washes=None) -> None:
    if washes is None:
        washes = WASHES
    prepare(n, scene)
    for poly in washes.get(n, []):
        for name in poly:
            if name not in scene.pts:
                raise SystemExit(f"I.{n}: wash vertex {name} missing")

    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H)
    cr = cairo.Context(surf)
    paint_ground(cr, book)

    # Same two header lines on every card. Book II type is teal on the cool
    # paper; there is no band behind it. Book I stays navy on cream.
    title = "Euclid's Elements"
    subtitle = f"Book {book} Proposition {n}"
    size = 48
    font(cr, size, bold=True)
    title_w = cr.text_extents(title).x_advance
    sub_w = cr.text_extents(subtitle).x_advance
    cr.set_source_rgb(*rgb(TEAL if book == 2 else NAVY))
    cr.move_to((W - title_w) / 2, 132)
    cr.show_text(title)
    cr.move_to((W - sub_w) / 2, 188)
    cr.show_text(subtitle)

    letter = 32.0
    minx, miny, maxx, maxy = scene.bounds()
    slot_top, slot_bot = 216, 688
    slot_l, slot_r = 36, W - 36
    # Letters sit 0.82em off the mark. Reserve that, plus half a glyph,
    # so a capital on the rim is not clipped.
    for _ in range(8):
        pad = letter * 1.45
        avail_w = slot_r - slot_l - 2 * pad
        avail_h = slot_bot - slot_top - 2 * pad
        gw, gh = max(maxx - minx, 1.0), max(maxy - miny, 1.0)
        scale = min(avail_w / gw, avail_h / gh)
        ox = W / 2 - (minx + maxx) / 2 * scale
        oy = (slot_top + pad + slot_bot - pad) / 2 + (miny + maxy) / 2 * scale

        def pt_of(p: V2) -> tuple[float, float]:
            return ox + p.x * scale, oy - p.y * scale

        boxes = []
        overflow = False
        for _name, (anchor, deg, r_em) in scene.labels.items():
            x, y = pt_of(anchor)
            ang = math.radians(deg)
            x += math.cos(ang) * r_em * letter
            y += -math.sin(ang) * r_em * letter
            font(cr, letter, italic=True)
            ext = cr.text_extents(_name[:1] or "A")
            half_w = ext.width / 2 + 2
            half_h = ext.height / 2 + 2
            boxes.append((x - half_w, y - half_h, x + half_w, y + half_h))
            if x - half_w < 16 or x + half_w > W - 16 or y - half_h < slot_top - 8 or y + half_h > H - 16:
                overflow = True
        overlap = False
        for i, a in enumerate(boxes):
            for b in boxes[i + 1 :]:
                if a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]:
                    # A hair of overlap is the italic sidebearing, not a collision.
                    ix = min(a[2], b[2]) - max(a[0], b[0])
                    iy = min(a[3], b[3]) - max(a[1], b[1])
                    if ix > 3 and iy > 3:
                        overlap = True
        if not overflow and not overlap:
            break
        letter = max(18.0, letter * 0.9)
        if letter <= 18.0:
            break

    def pt(name: str) -> tuple[float, float]:
        return pt_of(scene.at(name))

    def poly(names: tuple[str, ...]) -> None:
        x, y = pt(names[0])
        cr.move_to(x, y)
        for name in names[1:]:
            cr.line_to(*pt(name))
        cr.close_path()

    regions = washes.get(n, [])
    fill = SQUARE_FILL.get(n)
    for i, names in enumerate(regions):
        if fill is not None:
            # One very light wash. The plate does not draw these squares.
            cr.set_source_rgba(*rgb(fill[0]), fill[1])
        elif book == 2:
            # One sage wash. A second hue would say the rectangle and its
            # pieces differ, and gold would be the Book I plate again.
            cr.set_source_rgba(*rgb(SAGE), 0.62)
        elif len(regions) == 1 or n in SAME_WASH:
            cr.set_source_rgba(*rgb(WASH), 0.85)
        elif i == 0:
            cr.set_source_rgba(*rgb(WASH), 0.85)
        else:
            cr.set_source_rgba(*rgb(GOLD), 0.28)
        poly(names)
        cr.fill()

    def angle_radius(arm: str, vertex: str, other: str, reach: float) -> float:
        vv = scene.at(vertex)
        span = min(vv.dist(scene.at(arm)), vv.dist(scene.at(other)))
        # A fraction of the shorter arm. At least 1 is a plate radius, shared
        # by every angle in the group so a longer arm does not draw a bigger pie.
        if reach >= 1.0:
            return min(reach, span * 0.92)
        return reach * span

    def given_angle_radius(arm: str, vertex: str, other: str) -> float:
        # I.42's pie, in pixels on this card, converted back to plate units.
        # Cap at the shorter arm so a pie cannot run past the stroke.
        vv = scene.at(vertex)
        span = min(vv.dist(scene.at(arm)), vv.dist(scene.at(other)))
        return min(GIVEN_ANGLE_PIE_PX / scale, span * 0.92)

    # Pies under the ink, so the plate's strokes and letters stay as they
    # are. Each equality group is one color and one radius; the next group
    # is the other set. Larger first, so a smaller pie is not covered.
    # No entry: the I.42 rose pie, at the I.42 card size.
    groups = ANGLES.get(n, [])
    marks = ANGLE_MARK.get(n)
    if marks is None:
        marks = [(PIE_ALT, None)] * len(groups)
    if len(marks) != len(groups):
        raise SystemExit(f"I.{n}: angle mark count {len(marks)} != groups {len(groups)}")
    # Larger first, so a smaller pie is not covered. A hair (ANGLE_HAIR)
    # counts, so a second set drawn a hair larger is not painted over.
    def mark_size(i: int) -> float:
        reach = marks[i][1] or 0.0
        hairs = [
            ANGLE_HAIR.get((n, arm, vertex, other), 1.0)
            for arm, vertex, other in groups[i]
        ]
        return reach * max(hairs or [1.0])

    order = sorted(range(len(groups)), key=mark_size, reverse=True)
    for i in order:
        color, reach = marks[i]
        cr.set_source_rgba(*rgb(color), 0.86)
        for arm, vertex, other in groups[i]:
            radius = (
                given_angle_radius(arm, vertex, other)
                if reach is None
                else angle_radius(arm, vertex, other, reach)
            )
            hair = ANGLE_HAIR.get((n, arm, vertex, other))
            if hair:
                vv = scene.at(vertex)
                span = min(vv.dist(scene.at(arm)), vv.dist(scene.at(other)))
                radius = min(radius * hair, span * 0.92)
            pts = (
                angle_square(scene, arm, vertex, other, radius)
                if n in SQUARE_MARK
                else angle_wedge(scene, arm, vertex, other, radius)
            )
            cr.move_to(*pt_of(pts[0]))
            for p in pts[1:]:
                cr.line_to(*pt_of(p))
            cr.close_path()
            cr.fill()

    def clip_circles() -> None:
        if not scene.clip_box:
            return
        a, b = scene.clip_box
        x0, y0 = pt_of(a)
        x1, y1 = pt_of(b)
        cr.rectangle(min(x0, x1), min(y0, y1), abs(x1 - x0), abs(y1 - y0))
        cr.clip()

    cr.save()
    clip_circles()
    # show_text leaves the pen at the end of the subtitle. cairo_arc
    # joins that point to the arc, which drew a stroke from "Proposition"
    # into the circle (I.1, I.2, I.3, I.12, I.22).
    cr.new_path()
    line_book = {2: LINES2}.get(book, LINES)
    alt_book = {2: LINE_ALT2}.get(book, LINE_ALT)
    extra_book = {2: LINE_EXTRA2}.get(book, LINE_EXTRA)
    lit_segs = line_book.get(n, [])
    alt_segs = alt_book.get(n, [])
    extra = extra_book.get(n, [])
    extra_segs = [seg for _, segs in extra for seg in segs]
    for a, b in lit_segs + alt_segs + extra_segs:
        if a not in scene.pts or b not in scene.pts:
            raise SystemExit(f"I.{n}: line {a}{b} missing")
    lit_ink = {(a, b) for a, b in lit_segs + alt_segs + extra_segs} | {
        (b, a) for a, b in lit_segs + alt_segs + extra_segs
    }
    square_edges = list(SQUARE_QUIET.get(n, ()))
    square_ink = {(a, b) for a, b in square_edges} | {(b, a) for a, b in square_edges}
    # Construction stays the same ink as I.1. Only the named lines are lit.
    # A named side may be chained through a construction point (D on AB).
    # The highlight is the whole chord, drawn over the pieces, so the plate's
    # dot stays and the brick is not a second stroke beside a gap.
    ink = ink_of(book)
    cr.set_source_rgb(*rgb(ink))
    cr.set_line_width(3.2)
    cr.set_line_cap(cairo.LINE_CAP_ROUND)
    for name, r in scene.circs:
        x, y = pt(name)
        cr.arc(x, y, r * scale, 0, math.tau)
        cr.stroke()
    for a, b, via in scene.arc_list:
        pts = arc_points(a, b, via)
        if not pts:
            continue
        cr.move_to(*pt_of(V2(*pts[0])))
        for x, y in pts[1:]:
            cr.line_to(*pt_of(V2(x, y)))
        cr.stroke()
    cr.restore()

    cr.set_source_rgb(*rgb(ink))
    cr.set_line_width(3.2)
    cr.set_line_cap(cairo.LINE_CAP_ROUND)
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    for a, b in scene.segs:
        if (a, b) in lit_ink or (a, b) in square_ink:
            continue
        cr.move_to(*pt(a))
        cr.line_to(*pt(b))
        cr.stroke()

    # Brick, not the wash gold: gold on cream reads as mustard and fights
    # the navy type. A second equality takes the yellow, so the pairs read
    # as two sets. Labels stay navy, the color every other card uses.
    def stroke_lines(segs, color) -> None:
        cr.set_source_rgb(*rgb(color))
        cr.set_line_width(13)
        cr.set_line_cap(cairo.LINE_CAP_ROUND)
        for a, b in segs:
            cr.move_to(*pt(a))
            cr.line_to(*pt(b))
            cr.stroke()

    # Book II names its lines in copper. Brick is the Book I mark.
    stroke_lines(lit_segs, COPPER if book == 2 else BRICK)
    stroke_lines(alt_segs, PIE)
    for color, segs in extra:
        stroke_lines(segs, color)

    # A miss can cross a named side (EG across DF on I.8). The highlight is
    # drawn over the plate, so the unlit strokes go back on top and the
    # crossing stays. Other cards have no crossing to restore.
    if n == 8:
        cr.set_source_rgb(*rgb(ink))
        cr.set_line_width(3.2)
        cr.set_line_cap(cairo.LINE_CAP_ROUND)
        for a, b in scene.segs:
            if (a, b) in lit_ink:
                continue
            cr.move_to(*pt(a))
            cr.line_to(*pt(b))
            cr.stroke()

    cr.new_path()
    for p in scene.dot_pts:
        x, y = pt_of(p)
        cr.set_source_rgb(*rgb(ink))
        cr.arc(x, y, 4.2, 0, math.tau)
        cr.fill()

    for name, (anchor, deg, r_em) in scene.labels.items():
        x, y = pt_of(anchor)
        ang = math.radians(deg)
        x += math.cos(ang) * r_em * letter
        y += -math.sin(ang) * r_em * letter
        font(cr, letter, italic=True)
        cr.set_source_rgb(*rgb(TEAL if book == 2 else NAVY))
        ext = cr.text_extents(name)
        cr.move_to(x - (ext.x_bearing + ext.width / 2), y - (ext.y_bearing + ext.height / 2))
        cr.show_text(name)

    surf.write_to_png(out)


def functions_in(path: Path, prefix: str) -> dict[int, str]:
    text = path.read_text()
    out = {}
    for chunk in re.split(r"\npub fn ", text)[1:]:
        m = re.match(prefix + r"(\d+)", chunk)
        if not m:
            continue
        n = int(m.group(1))
        body = chunk.split("{", 1)[1]
        depth = 1
        i = 0
        while i < len(body) and depth:
            if body[i] == "{":
                depth += 1
            elif body[i] == "}":
                depth -= 1
            i += 1
        out[n] = body[: i - 1]
    return out


# The constructed pentagon. The circle is the given setting, not a second wash.
WASHES4 = {
    11: [("A", "B", "C", "D", "E")],
    12: [("G", "H", "K", "L", "M")],
}

# II.1: the rectangle contained by the two straight-lines equals the sum of
# the rectangles contained by the uncut line and each piece. One wash — two
# hues would say the whole and the pieces differ. A is a line, not a second
# area, so it takes no wash. A and BC are the two straight-lines the
# enunciation names, so they take the copper (LINES2), not the Book I brick.
WASHES2 = {
    1: [("B", "C", "H", "G")],
}

# Named straight-lines, book by book. Book I is LINES. A produced ray is
# not the subject: only the named piece.
LINES2: dict[int, list[tuple[str, str]]] = {
    # A, the uncut straight-line, and BC, the line cut into pieces. The
    # enunciation names both. The rectangle they contain is the wash. D
    # and E lie on BC, so the cut line is the whole chord, not the pieces.
    1: [("A0", "A1"), ("B", "C")],
}
LINE_ALT2: dict[int, list[tuple[str, str]]] = {}
LINE_EXTRA2: dict[int, list[tuple[tuple[int, int, int], tuple[tuple[str, str], ...]]]] = {}


def main() -> None:
    args = sys.argv[1:]
    book = 1
    if "--book" in args:
        i = args.index("--book")
        book = int(args[i + 1])
        args = args[:i] + args[i + 2 :]
    if book == 1:
        fns = functions()
        washes = WASHES
        wanted = [int(a) for a in args if a.isdigit()] or (list(range(1, 37)) + [41, 42, 43, 44, 45, 46, 47, 48])
    else:
        fns = functions_in(ROOT / "src" / "figure" / f"book{book}.rs", f"book{book}_prop")
        washes = {2: WASHES2, 4: WASHES4}.get(book, {})
        wanted = [int(a) for a in args if a.isdigit()] or sorted(fns)
